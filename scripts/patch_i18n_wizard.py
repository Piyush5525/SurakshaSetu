for name, block in (("en.ts", EN), ("hi.ts", HI)):
    p = I / name
    s = p.read_text(encoding="utf-8")
    anchor = "  receipt: {"
    assert anchor in s and "  w: {" not in s, name
    p.write_text(s.replace(anchor, block + anchor, 1), encoding="utf-8", newline="\n")
